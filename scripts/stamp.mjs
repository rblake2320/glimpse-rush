// Run before every deploy (npm run deploy):
//  1. prototype/version.json — open pages notice a new version and reload themselves (never mid-round)
//  2. prototype/_headers     — security headers; the CSP allows inline scripts only by their exact sha256,
//                              recomputed here so the policy always matches the deployed pages
import { execSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";

const P = (f) => new URL("../prototype/" + f, import.meta.url);
let commit = "dev";
try { commit = execSync("git rev-parse --short HEAD").toString().trim(); } catch {}
const build = `${commit}-${Date.now().toString(36)}`;
writeFileSync(P("version.json"), JSON.stringify({ build }) + "\n");

const hashes = new Set();
for (const page of ["index.html", "admin/index.html", "404.html"]) {
  const html = readFileSync(P(page), "utf8");
  for (const m of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) hashes.add(`'sha256-${createHash("sha256").update(m[1].replace(/\r\n?/g, "\n"), "utf8").digest("base64")}'`); // browsers hash after normalising line endings
}
const csp = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].join(" ")}`,
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com",
  "font-src https://fonts.gstatic.com",
  "img-src 'self' data: blob:",
  "connect-src 'self' wss://glimpse-rush.pages.dev wss://*.glimpse-rush.pages.dev",
  "object-src 'none'", "base-uri 'self'", "form-action 'self'", "frame-ancestors 'none'",
].join("; ");
writeFileSync(P("_headers"), `# Generated by scripts/stamp.mjs at deploy. Edit the generator, not this file.
/*
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  Strict-Transport-Security: max-age=31536000
  X-Frame-Options: DENY
  Cross-Origin-Opener-Policy: same-origin
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()
  Content-Security-Policy: ${csp}
/photos/*.jpg
  Cache-Control: public, max-age=31536000, immutable
/favicon.ico
  Cache-Control: public, max-age=86400
/icon-*
  Cache-Control: public, max-age=86400
/apple-touch-icon.png
  Cache-Control: public, max-age=86400
/og.png
  Cache-Control: public, max-age=86400
/version.json
  Cache-Control: no-store
/admin/*
  X-Robots-Tag: noindex, nofollow
  Cache-Control: no-store
/api/*
  Cache-Control: no-store
`);
console.log("build", build, "| CSP script hashes:", hashes.size);
